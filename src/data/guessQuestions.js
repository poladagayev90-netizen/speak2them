// In-call "Guess It" deck (bil bakalım). Each card asks for a NUMBER nobody
// actually knows — how heavy an elephant's ear is, how many hairs are on a
// head. Both peers write a guess, the closer one wins the round, and then they
// have to defend the number out loud. The number is the excuse; the arguing is
// the lesson.
//
// SHAPE
//   cat   – emoji + category, shown as a chip. Emoji here is CONTENT, not an
//           icon, which is the one place the icon rule allows it.
//   q     – the question in English, A2 vocabulary. This is what gets read.
//   az/tr – the same question in the learner's L1, behind a "Translate"
//           toggle. Pre-written on purpose: a call is the worst possible
//           moment for a network round-trip, and a stored translation costs
//           nothing, works offline and never drifts.
//   a     – the answer as a positive number. NEVER zero or negative: the
//           scoring is ratio-based (see utils/guessGame.js) and ln(0) is not a
//           number. Questions that would naturally answer 0 or minus are
//           reworded ("how many degrees BELOW zero is space" → 270).
//   unit  – shown next to the input and the answer, so nobody guesses grams
//           against kilograms.
//   fact  – one line revealed with the answer. This is the payoff; without it
//           the round just ends.
//
// ABOUT THE NUMBERS: these are the commonly cited approximations, not measured
// constants — an elephant's ear is not exactly 50 kg. That is fine, and it is
// why the scoring compares ORDERS OF MAGNITUDE rather than exact differences:
// being 2x off beats being 20x off, and nobody ever needs the decimal.
//
// ORDER MATTERS: the game picks a random start index and then walks forward
// one card at a time (cardIndex is synced to both peers through Firestore).
// The list below is hand-mixed so two animal questions never sit next to each
// other. NEVER shuffle at runtime — the two peers would land on different
// cards. Same rule as tabooWords.js and debateTopics.js.

