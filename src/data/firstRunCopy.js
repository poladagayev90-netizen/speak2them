// t('ob.avail.sub', { city: 'Baku' }) in `lang`, English when the key is missing.
export function firstRunText(lang, key, vars) {
  const raw = (FIRST_RUN_COPY[lang] && FIRST_RUN_COPY[lang][key]) ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}
