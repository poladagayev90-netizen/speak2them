const stored = (() => {
  try { return localStorage.getItem(LANG_STORAGE_KEY); } catch { return null; }
})();

i18n
  .use(initReactI18next)
  .init({
    resources: { az: az, tr: tr },
    lng: stored === 'tr' ? 'tr' : 'az',
    fallbackLng: 'az',
    defaultNS: 'common',
    ns: ['common', 'nav', 'headers', 'profile', 'ranking', 'teacher', 'analysis'],
    interpolation: { escapeValue: false },
    react: { useSuspense: false },
  });

// Dili dəyişir və localStorage-ə yazır. Firestore yazısı çağıran tərəfdədir
// (Profile) — i18n modulu Firebase-dən asılı olmamalıdır.
export function setLanguage(code) {
  const lang = code === 'tr' ? 'tr' : 'az';
  i18n.changeLanguage(lang);
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* private mode */ }
  return lang;
}

export default i18n;
